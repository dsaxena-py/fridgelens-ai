"""Export a trained model to ONNX with a model card and the SQL that registers it in Supabase."""

from __future__ import annotations

import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path

from . import classes


def _sql(value) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def registration_sql(card: dict) -> str:
    """Insert into model_versions + detector_classes. Activation is a separate, commented step."""
    rows = ",\n".join(f"  ({c['index']}, {_sql(c['slug'])})" for c in card["classes"])
    metrics = json.dumps(card["metrics"], separators=(",", ":"))
    name = _sql(card["name"])
    return f"""-- Register {card['name']} (generated by meallens_ai export). Safe to re-run.
insert into model_versions (name, architecture, weights_uri, input_size, conf_threshold, iou_threshold, metrics)
values ({name}, {_sql(card['architecture'])}, {_sql(card['weights_uri'])}, {card['input_size']},
        {card['conf_threshold']}, {card['iou_threshold']}, {_sql(metrics)}::jsonb)
on conflict (name) do update
  set architecture = excluded.architecture, weights_uri = excluded.weights_uri, input_size = excluded.input_size,
      conf_threshold = excluded.conf_threshold, iou_threshold = excluded.iou_threshold, metrics = excluded.metrics;

insert into detector_classes (model_version_id, class_index, label, ingredient_id)
select mv.id, v.class_index, v.label, i.id
from model_versions mv
cross join (values
{rows}
) as v(class_index, label)
join ingredients i on i.slug = v.label
where mv.name = {name}
on conflict (model_version_id, class_index) do update
  set label = excluded.label, ingredient_id = excluded.ingredient_id;

-- Check: should return {len(card['classes'])}.
select count(*) from detector_classes dc join model_versions mv on mv.id = dc.model_version_id where mv.name = {name};

-- To make this the model the backend loads, run these two statements together:
-- update model_versions set is_active = false where is_active;
-- update model_versions set is_active = true where name = {name};
"""


def export(weights: Path, name: str, out: Path, conf: float, iou: float = 0.5, imgsz: int = 640,
           metrics: dict | None = None, weights_uri: str | None = None) -> dict:
    """Write <out>/<name>.onnx, model_card.json and register_model.sql."""
    from ultralytics import YOLO

    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    model = YOLO(str(weights))
    names = classes.names()
    model_names = [model.names[i] for i in sorted(model.names)]
    if model_names != names:
        raise ValueError(f"model classes {model_names} do not match configs/classes.yaml {names}")
    onnx_tmp = Path(model.export(format="onnx", imgsz=imgsz, simplify=True, dynamic=False))
    onnx_path = out / f"{name}.onnx"
    shutil.move(str(onnx_tmp), onnx_path)

    train_args = (getattr(model, "ckpt", None) or {}).get("train_args", {})
    architecture = Path(str(train_args.get("model", "yolo"))).stem
    card = {
        "name": name,
        "architecture": architecture,
        "weights_uri": weights_uri or f"{name}.onnx",
        "sha256": hashlib.sha256(onnx_path.read_bytes()).hexdigest(),
        "input_size": imgsz,
        "conf_threshold": conf,
        "iou_threshold": iou,
        "output": "raw head (1, 4 + num_classes, N): cx, cy, w, h in input pixels, then class scores; NMS not included",
        "classes": [{"index": c.index, "slug": c.slug} for c in classes.load_classes()],
        "metrics": metrics or {},
        "exported_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    (out / "model_card.json").write_text(json.dumps(card, indent=2) + "\n")
    (out / "register_model.sql").write_text(registration_sql(card))
    return card


def metrics_from_report(report: dict) -> dict:
    """The summary stored in model_versions.metrics, taken from an evaluate() report."""
    m = {"split": report["split"], "images": report["images"],
         "precision": round(report["macro"]["precision"], 4), "recall": round(report["macro"]["recall"], 4),
         "f1": round(report["macro"]["f1"], 4), "map50": round(report["map"]["map50"], 4),
         "map50_95": round(report["map"]["map50_95"], 4)}
    if report.get("latency"):
        m["cpu_ms_p50"] = report["latency"]["cpu_ms_p50"]
    return m
